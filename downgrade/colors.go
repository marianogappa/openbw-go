var opaqueAlpha = math.Float32bits(1)

func colorByFootprint(footprint []byte) (uint32, bool) {
	if len(footprint) != cclrFootprintSize || binary.LittleEndian.Uint32(footprint[12:]) != opaqueAlpha {
		return 0, false
	}
	r, g, b := binary.LittleEndian.Uint32(footprint), binary.LittleEndian.Uint32(footprint[4:]), binary.LittleEndian.Uint32(footprint[8:])
	for _, c := range colorFootprints {
		if c.r == r && c.g == g && c.b == b {
			return c.id, true
		}
	}
	return 0, false
}

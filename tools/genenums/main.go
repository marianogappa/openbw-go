package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"regexp"
	"strconv"
	"strings"
	"unicode"
)

type enumerator struct {
	name  string
	value int
}

type enumBlock struct {
	cppName     string
	typed       bool
	enumerators []enumerator
}

var (
	enumStructPattern = regexp.MustCompile(`^enum struct (\w+) : int \{$`)
	namespacePattern  = regexp.MustCompile(`^namespace (\w+)\s*\{?$`)
	anonymousEnum     = regexp.MustCompile(`^enum\s*\{?$`)
	shiftPattern      = regexp.MustCompile(`^(\d+)\s*<<\s*(\d+)$`)
)

func main() {
	input := flag.String("in", "ref/openbw/bwenums.h", "path to bwenums.h")
	output := flag.String("out", "bwgame/enums.go", "path to the generated Go file")
	namesOutput := flag.String("names", "names.go", "path to the generated name tables of package openbw")
	flag.Parse()
	if err := run(*input, *output, *namesOutput); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(input, output, namesOutput string) error {
	source, err := os.ReadFile(input)
	if err != nil {
		return err
	}
	blocks, err := parseBlocks(source)
	if err != nil {
		return err
	}
	code, err := render(blocks)
	if err != nil {
		return err
	}
	if err := os.WriteFile(output, code, 0o644); err != nil {
		return err
	}
	names, err := renderNames(blocks)
	if err != nil {
		return err
	}
	return os.WriteFile(namesOutput, names, 0o644)
}

var nameTables = []struct{ cppName, goName string }{
	{"UnitTypes", "unitTypeNames"},
	{"TechTypes", "techNames"},
	{"UpgradeTypes", "upgradeNames"},
}

func renderNames(blocks []enumBlock) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by tools/genenums from ref/openbw/bwenums.h. DO NOT EDIT.\n\n")
	b.WriteString("package openbw\n\n")
	for _, table := range nameTables {
		block, ok := findBlock(blocks, table.cppName)
		if !ok {
			return nil, fmt.Errorf("enum %s not found", table.cppName)
		}
		names := map[int]string{}
		size := 0
		for _, e := range block.enumerators {
			if e.name == "None" {
				continue
			}
			names[e.value] = strings.ReplaceAll(e.name, "_", " ")
			size = max(size, e.value+1)
		}
		fmt.Fprintf(&b, "var %s = [...]string{\n", table.goName)
		for v := range size {
			fmt.Fprintf(&b, "\t%q,\n", names[v])
		}
		b.WriteString("}\n\n")
	}
	return format.Source(b.Bytes())
}

func findBlock(blocks []enumBlock, cppName string) (enumBlock, bool) {
	for _, block := range blocks {
		if block.cppName == cppName {
			return block, true
		}
	}
	return enumBlock{}, false
}

func parseBlocks(source []byte) ([]enumBlock, error) {
	var blocks []enumBlock
	var current *enumBlock
	pendingNamespace := ""
	nextValue := 0
	scanner := bufio.NewScanner(bytes.NewReader(source))
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if line == "" || line == "{" || strings.HasPrefix(line, "#") || line == "namespace bwgame {" {
			continue
		}
		if current == nil {
			if m := enumStructPattern.FindStringSubmatch(line); m != nil {
				current = &enumBlock{cppName: m[1], typed: true}
				nextValue = 0
				continue
			}
			if m := namespacePattern.FindStringSubmatch(line); m != nil {
				pendingNamespace = m[1]
				continue
			}
			if anonymousEnum.MatchString(line) && pendingNamespace != "" {
				current = &enumBlock{cppName: pendingNamespace}
				nextValue = 0
				continue
			}
			if line == "}" {
				pendingNamespace = ""
			}
			continue
		}
		if strings.HasPrefix(line, "}") {
			blocks = append(blocks, *current)
			current = nil
			continue
		}
		e, err := parseEnumerator(line, nextValue)
		if err != nil {
			return nil, err
		}
		current.enumerators = append(current.enumerators, e)
		nextValue = e.value + 1
	}
	if err := scanner.Err(); err != nil {
		return nil, err
	}
	if current != nil {
		return nil, fmt.Errorf("unterminated enum %s", current.cppName)
	}
	return blocks, nil
}

func parseEnumerator(line string, implicitValue int) (enumerator, error) {
	line = strings.TrimSuffix(line, ",")
	name, expression, hasValue := strings.Cut(line, "=")
	name = strings.TrimSpace(name)
	if !hasValue {
		return enumerator{name: name, value: implicitValue}, nil
	}
	value, err := evaluate(strings.TrimSpace(expression))
	if err != nil {
		return enumerator{}, fmt.Errorf("enumerator %s: %w", name, err)
	}
	return enumerator{name: name, value: value}, nil
}

func evaluate(expression string) (int, error) {
	if m := shiftPattern.FindStringSubmatch(expression); m != nil {
		base, _ := strconv.Atoi(m[1])
		shift, _ := strconv.Atoi(m[2])
		return base << shift, nil
	}
	return strconv.Atoi(expression)
}

func goName(cppName string) string {
	parts := strings.Split(cppName, "_")
	var b strings.Builder
	for i, part := range parts {
		if part == "" {
			continue
		}
		if i > 0 && endsWithDigit(b.String()) && startsWithDigit(part) {
			b.WriteByte('_')
		}
		runes := []rune(part)
		runes[0] = unicode.ToUpper(runes[0])
		b.WriteString(string(runes))
	}
	return b.String()
}

func endsWithDigit(s string) bool {
	return s != "" && s[len(s)-1] >= '0' && s[len(s)-1] <= '9'
}

func startsWithDigit(s string) bool {
	return s != "" && s[0] >= '0' && s[0] <= '9'
}

func render(blocks []enumBlock) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by tools/genenums from ref/openbw/bwenums.h. DO NOT EDIT.\n\n")
	b.WriteString("package bwgame\n\n")
	seen := map[string]bool{}
	for _, block := range blocks {
		typeName := goName(block.cppName)
		if block.typed {
			fmt.Fprintf(&b, "type %s int\n\n", typeName)
		}
		b.WriteString("const (\n")
		for _, e := range block.enumerators {
			name := typeName + goName(e.name)
			if seen[name] {
				return nil, fmt.Errorf("duplicate Go name %s", name)
			}
			seen[name] = true
			if block.typed {
				fmt.Fprintf(&b, "\t%s %s = %d\n", name, typeName, e.value)
			} else {
				fmt.Fprintf(&b, "\t%s = %d\n", name, e.value)
			}
		}
		b.WriteString(")\n\n")
	}
	return format.Source(b.Bytes())
}

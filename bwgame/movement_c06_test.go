func TestGetUniqueSidedPositionsWithinBoundsC06(t *testing.T) {
	fx := parseMovementC06Fixture(t)
	f := newMovementC06Functions(fx.contours)
	for _, c := range fx.cases('U') {
		bounds := Rect{From: Xy{X: int32(c[1]), Y: int32(c[2])}, To: Xy{X: int32(c[3]), Y: int32(c[4])}}
		from := Xy{X: int32(c[5]), Y: int32(c[6])}
		to := Xy{X: int32(c[7]), Y: int32(c[8])}
		got := f.getUniqueSidedPositionsWithinBounds(&from, &to, bounds)
		want := Rect{From: Xy{X: int32(c[10]), Y: int32(c[11])}, To: Xy{X: int32(c[12]), Y: int32(c[13])}}
		if got != (c[9] != 0) || from != want.From || to != want.To {
			t.Fatalf("getUniqueSidedPositionsWithinBounds%v = %v %v %v", c, got, from, to)
		}
	}
}

func TestCanFitAtC06(t *testing.T) {
	fx := parseMovementC06Fixture(t)
	f := newMovementC06Functions(fx.contours)
	for _, c := range fx.cases('F') {
		pos := Xy{X: int32(c[1]), Y: int32(c[2])}
		inner := [4]int32{int32(c[3]), int32(c[4]), int32(c[5]), int32(c[6])}
		if got := f.canFitAt(pos, inner); got != (c[7] != 0) {
			t.Fatalf("canFitAt%v = %v", c, got)
		}
	}
}

func TestCheckUnitMovementTerrainCollisionC06(t *testing.T) {
	fx := parseMovementC06Fixture(t)
	f := newMovementC06Functions(fx.contours)
	for _, c := range fx.cases('M') {
		u := &Unit{}
		u.Sprite = &Sprite{Position: Xy{X: int32(c[5]), Y: int32(c[6])}}
		u.UnitType = &UnitTypeT{Dimensions: Rect{From: Xy{X: int32(c[7]), Y: int32(c[8])}, To: Xy{X: int32(c[9]), Y: int32(c[10])}}}
		u.TerrainNoCollisionBounds = Rect{From: Xy{X: int32(c[1]), Y: int32(c[2])}, To: Xy{X: int32(c[3]), Y: int32(c[4])}}
		got := f.checkUnitMovementTerrainCollision(u, Xy{X: int32(c[11]), Y: int32(c[12])})
		wantBounds := Rect{From: Xy{X: int32(c[14]), Y: int32(c[15])}, To: Xy{X: int32(c[16]), Y: int32(c[17])}}
		if got != (c[13] != 0) || u.TerrainNoCollisionBounds != wantBounds {
			t.Fatalf("checkUnitMovementTerrainCollision%v = %v %v", c, got, u.TerrainNoCollisionBounds)
		}
	}
}


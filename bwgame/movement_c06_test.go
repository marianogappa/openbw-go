type movementC06Fixture struct {
	contours [4][]Contour
	lines    [][]int64
}

func parseMovementC06Fixture(t *testing.T) movementC06Fixture {
	var fx movementC06Fixture
	scanner := bufio.NewScanner(strings.NewReader(movementC06ReferenceOutput))
	contourIndex := 0
	for scanner.Scan() {
		fields := strings.Fields(scanner.Text())
		if len(fields) == 0 {
			continue
		}
		values := make([]int64, len(fields))
		values[0] = int64(fields[0][0])
		for i := 1; i < len(fields); i++ {
			v, err := strconv.ParseInt(fields[i], 10, 64)
			if err != nil {
				t.Fatal(err)
			}
			values[i] = v
		}
		switch fields[0] {
		case "C":
			contourIndex = int(values[1])
		case "c":
			fx.contours[contourIndex] = append(fx.contours[contourIndex], Contour{
				V:     [3]int32{int32(values[1]), int32(values[2]), int32(values[3])},
				Dir:   uint(values[4]),
				Flags: uint8(values[5]),
			})
		default:
			fx.lines = append(fx.lines, values)
		}
	}
	return fx
}

func newMovementC06Functions(contours [4][]Contour) *StateFunctions {
	game := NewGameState()
	game.Regions.Contours = contours
	return NewStateFunctions(NewState(nil, game))
}

func (fx movementC06Fixture) cases(kind byte) [][]int64 {
	var r [][]int64
	for _, l := range fx.lines {
		if l[0] == int64(kind) {
			r = append(r, l)
		}
	}
	return r
}

func TestUnitTurnRateC06(t *testing.T) {
	fx := parseMovementC06Fixture(t)
	f := newMovementC06Functions(fx.contours)
	for _, c := range fx.cases('T') {
		u := &Flingy{FlingyTurnRate: Fp8FromRaw(int32(c[1])), FlingyMovementType: int32(c[2])}
		got := f.unitTurnRate(u, DirectionTFromRaw(int8(c[3])))
		if int64(got.RawValue) != c[4] {
			t.Fatalf("unitTurnRate%v = %d", c, got.RawValue)
		}
	}
}


package bwgame

import (
	"fmt"
	"strings"
	"testing"
)

func newGeometryTestFunctions() *StateFunctions {
	return NewStateFunctions(NewState(&GlobalState{}, NewGameState()))
}

func TestGeometryMatchesCppReference(t *testing.T) {
	f := newGeometryTestFunctions()
	rectIndex := 0
	for _, line := range strings.Split(strings.TrimSpace(geometryReferenceOutputC01), "\n") {
		got := geometryCaseOutput(f, line, &rectIndex)
		if got != line {
			t.Errorf("got %q, want %q", got, line)
		}
	}
}

func geometryCaseOutput(f *StateFunctions, line string, rectIndex *int) string {
	var kind string
	fmt.Sscan(line, &kind)
	switch kind {
	case "L":
		var x, y int32
		fmt.Sscan(line[2:], &x, &y)
		p := Xy{X: x, Y: y}
		return fmt.Sprintf("L %d %d %d %d", x, y, f.xyLength(p), f.xyDirection(p).RawValue)
	case "F":
		var x, y int32
		fmt.Sscan(line[2:], &x, &y)
		p := XyFp8{X: Fp8FromRaw(x), Y: Fp8FromRaw(y)}
		return fmt.Sprintf("F %d %d %d %d", x, y, f.xyLengthFP8(p).RawValue, f.xyDirectionFP8(p).RawValue)
	case "D":
		var d int32
		fmt.Sscan(line[2:], &d)
		dir := DirectionTFromRaw(int8(d))
		a := f.directionXY(dir, Fp8FromRaw(1234))
		b := f.directionXYInt(dir, -37)
		index := f.directionIndex(dir)
		return fmt.Sprintf("D %d %d %d %d %d %d %d", d, index, f.directionFromIndex(index).RawValue, a.X.RawValue, a.Y.RawValue, b.X.RawValue, b.Y.RawValue)
	case "R":
		output := rectCaseOutput(f, rectCasesC01[*rectIndex])
		*rectIndex++
		return output
	}
	return "unknown case " + kind
}

var rectCasesC01 = []Rect{
	{From: Xy{X: 0, Y: 0}, To: Xy{X: 5, Y: 5}},
	{From: Xy{X: 35, Y: 45}, To: Xy{X: 50, Y: 60}},
	{From: Xy{X: 15, Y: 0}, To: Xy{X: 20, Y: 10}},
	{From: Xy{X: 0, Y: 50}, To: Xy{X: 12, Y: 70}},
	{From: Xy{X: 12, Y: 22}, To: Xy{X: 14, Y: 24}},
}

func rectCaseOutput(f *StateFunctions, b Rect) string {
	a := Rect{From: Xy{X: 10, Y: 20}, To: Xy{X: 30, Y: 40}}
	d := f.rectDifference(a, b)
	np := f.nearestPosInRect(b.From, a)
	return fmt.Sprintf("R %d %d %d %d", d.X, d.Y, np.X, np.Y)
}

